// Fails when the desktop renderer gains a way to run programs or reach a
// privileged API it did not have before. This is deliberately narrow: it
// checks the four facts that are mechanically decidable from the tree, and it
// does not claim that the pinned plugin presets grant nothing beyond what the
// app calls — that review needs the crate's permission files, which are not
// vendored here.
import fs from "node:fs";
import path from "node:path";

const root = new URL("..", import.meta.url).pathname.replace(/^\/(\w:)/, "$1");
const read = (relative) => fs.readFileSync(path.join(root, relative), "utf8");
const fail = [];
const ok = [];

// 1. No shell plugin: without it the webview cannot spawn a process at all,
//    and every privileged action must go through a declared #[command].
for (const file of ["package.json", "package-lock.json"]) {
  if (read(file).includes("@tauri-apps/plugin-shell")) {
    fail.push(`${file} depends on @tauri-apps/plugin-shell`);
  } else {
    ok.push(`${file} has no shell plugin`);
  }
}

// 2. No capability or permission document grants the shell plugin either,
//    which would be the same hole by a different name.
const tauriFiles = [
  "src-tauri/tauri.conf.json",
  ...fs
    .readdirSync(path.join(root, "src-tauri/capabilities"))
    .map((f) => `src-tauri/capabilities/${f}`),
  ...fs
    .readdirSync(path.join(root, "src-tauri/permissions"))
    .flatMap((f) => (f.endsWith(".toml") ? [`src-tauri/permissions/${f}`] : [])),
];
for (const file of tauriFiles) {
  if (
    /"shell:|shell:allow-(execute|spawn|stdin-write)|"withGlobalTauri"\s*:\s*true/.test(read(file))
  ) {
    fail.push(`${file} grants shell execution or a global privileged API`);
  }
}
ok.push(
  `${tauriFiles.length} capability/permission documents name no shell privilege and no global Tauri API`,
);

// 3. Opening a path or revealing an item in a folder hands a path to the OS
//    shell's default handler. The app only ever opens https/mailto URLs, so a
//    capability must never name those permissions.
for (const file of tauriFiles) {
  if (/allow-open-path|reveal-item-in-dir/.test(read(file))) {
    fail.push(`${file} grants opener path/reveal permissions the app never calls`);
  }
}
ok.push("no capability grants opener path or reveal permissions");

// 4. Every permission a capability names must exist, and every autogenerated
//    permission file must carry a real identifier — a renamed command whose
//    allow-file was not regenerated fails a Windows build, and this is the
//    cheapest place to catch a typo.
const capabilityNames = new Set();
for (const file of tauriFiles) {
  for (const match of read(file).matchAll(/"((?:allow|deny)-[a-z0-9-]+)"/g))
    capabilityNames.add(match[1]);
  for (const match of read(file).matchAll(/^\s*"((?:allow|deny)-[a-z0-9-]+)"/gm))
    capabilityNames.add(match[1]);
}
// Autogenerated permission files are named after the command they cover
// (`secure_defrag.toml`), not after the permission (`allow-secure-defrag`).
const permissionFile = (name) => `${name.replace(/^(allow|deny)-/, "").replace(/-/g, "_")}.toml`;
const missing = [...capabilityNames].filter(
  (name) =>
    !fs.existsSync(path.join(root, "src-tauri/permissions/autogenerated", permissionFile(name))),
);
if (missing.length) fail.push(`capabilities name permissions with no file: ${missing.join(", ")}`);
else ok.push(`${capabilityNames.size} named permissions all exist`);

for (const file of fs.readdirSync(path.join(root, "src-tauri/permissions/autogenerated"))) {
  const text = read(`src-tauri/permissions/autogenerated/${file}`);
  if (!/identifier = "allow-/.test(text))
    fail.push(`src-tauri/permissions/autogenerated/${file} declares no identifier`);
}

console.log(`Checking renderer privilege envelope`);
for (const line of ok) console.log(`  ok: ${line}`);
if (fail.length) {
  for (const line of fail) console.error(`  FAIL: ${line}`);
  process.exit(1);
}
